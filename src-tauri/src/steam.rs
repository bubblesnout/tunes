//! "Add Tunes to Steam": registers Tunes as a non-Steam shortcut for the most recent Steam
//! account and installs its library artwork (capsules, hero, logo, icon).
//!
//! Shortcuts live in `userdata/<accountid>/config/shortcuts.vdf`, a binary KeyValues file.
//! We parse it fully, change only the Tunes entry and write everything else back unchanged
//! (after taking a `.bak` copy). Steam reads the file at startup, so a running Steam needs a
//! restart to pick up the change.

use anyhow::{anyhow, bail, Context, Result};
use serde::Serialize;
use std::path::{Path, PathBuf};

const APP_NAME: &str = "Tunes";

// Artwork generated by scripts/steam-art.mjs (art/steam), embedded in the binary.
const ART_CAPSULE: &[u8] = include_bytes!("../../art/steam/capsule.png");
const ART_WIDE: &[u8] = include_bytes!("../../art/steam/wide.png");
const ART_HERO: &[u8] = include_bytes!("../../art/steam/hero.png");
const ART_LOGO: &[u8] = include_bytes!("../../art/steam/logo.png");
const ART_ICON: &[u8] = include_bytes!("../../art/steam/icon.png");

// ---------- Steam overlay compatibility -------------------------------------------------

/// Steam sets these for anything it launches, including non-Steam shortcuts.
pub fn launched_by_steam() -> bool {
    ["SteamGameId", "SteamOverlayGameId", "SteamClientLaunch"]
        .iter()
        .any(|v| std::env::var_os(v).is_some_and(|x| !x.is_empty()))
}

pub fn overlay_compat_active(setting: bool) -> bool {
    cfg!(windows) && setting && launched_by_steam()
}

// ---------- binary KeyValues (shortcuts.vdf) ---------------------------------------------

#[derive(Debug, Clone, PartialEq)]
enum Value {
    Map(Vec<(String, Value)>),
    Str(String),
    Int(i32),
    Float(f32),
    U64(u64),
}

struct Reader<'a> {
    b: &'a [u8],
    i: usize,
}

impl<'a> Reader<'a> {
    fn byte(&mut self) -> Result<u8> {
        let v = *self.b.get(self.i).ok_or_else(|| anyhow!("unexpected end of shortcuts.vdf"))?;
        self.i += 1;
        Ok(v)
    }
    fn take(&mut self, n: usize) -> Result<&'a [u8]> {
        let s = self.b.get(self.i..self.i + n).ok_or_else(|| anyhow!("unexpected end of shortcuts.vdf"))?;
        self.i += n;
        Ok(s)
    }
    fn cstr(&mut self) -> Result<String> {
        let start = self.i;
        while self.byte()? != 0 {}
        Ok(String::from_utf8_lossy(&self.b[start..self.i - 1]).into_owned())
    }
    fn map(&mut self) -> Result<Vec<(String, Value)>> {
        let mut out = Vec::new();
        loop {
            let t = self.byte()?;
            if t == 0x08 {
                return Ok(out);
            }
            let key = self.cstr()?;
            let v = match t {
                0x00 => Value::Map(self.map()?),
                0x01 => Value::Str(self.cstr()?),
                0x02 => Value::Int(i32::from_le_bytes(self.take(4)?.try_into()?)),
                0x03 => Value::Float(f32::from_le_bytes(self.take(4)?.try_into()?)),
                0x07 => Value::U64(u64::from_le_bytes(self.take(8)?.try_into()?)),
                other => bail!("unsupported value type 0x{other:02x} in shortcuts.vdf"),
            };
            out.push((key, v));
        }
    }
}

fn parse_vdf(bytes: &[u8]) -> Result<Vec<(String, Value)>> {
    let mut r = Reader { b: bytes, i: 0 };
    r.map()
}

fn write_map(out: &mut Vec<u8>, m: &[(String, Value)]) {
    for (k, v) in m {
        let (t, body): (u8, Vec<u8>) = match v {
            Value::Map(inner) => {
                let mut b = Vec::new();
                write_map(&mut b, inner);
                (0x00, b)
            }
            Value::Str(s) => (0x01, [s.as_bytes(), &[0]].concat()),
            Value::Int(n) => (0x02, n.to_le_bytes().to_vec()),
            Value::Float(f) => (0x03, f.to_le_bytes().to_vec()),
            Value::U64(n) => (0x07, n.to_le_bytes().to_vec()),
        };
        out.push(t);
        out.extend_from_slice(k.as_bytes());
        out.push(0);
        out.extend_from_slice(&body);
    }
    out.push(0x08);
}

fn serialize_vdf(root: &[(String, Value)]) -> Vec<u8> {
    let mut out = Vec::new();
    write_map(&mut out, root);
    out
}

fn get<'a>(m: &'a [(String, Value)], key: &str) -> Option<&'a Value> {
    m.iter().find(|(k, _)| k.eq_ignore_ascii_case(key)).map(|(_, v)| v)
}

fn get_str<'a>(m: &'a [(String, Value)], key: &str) -> Option<&'a str> {
    match get(m, key) {
        Some(Value::Str(s)) => Some(s),
        _ => None,
    }
}

// ---------- locating Steam --------------------------------------------------------------

pub fn steam_root() -> Option<PathBuf> {
    #[cfg(windows)]
    {
        if let Some(p) = reg_string("Software\\Valve\\Steam", "SteamPath") {
            let p = PathBuf::from(p.replace('/', "\\"));
            if p.join("userdata").is_dir() {
                return Some(p);
            }
        }
        for var in ["ProgramFiles(x86)", "ProgramFiles"] {
            if let Ok(pf) = std::env::var(var) {
                let p = Path::new(&pf).join("Steam");
                if p.join("userdata").is_dir() {
                    return Some(p);
                }
            }
        }
        None
    }
    #[cfg(not(windows))]
    {
        let home = dirs::home_dir()?;
        [".steam/steam", ".local/share/Steam", ".var/app/com.valvesoftware.Steam/.local/share/Steam"]
            .iter()
            .map(|p| home.join(p))
            .find(|p| p.join("userdata").is_dir())
    }
}

#[cfg(windows)]
fn reg_string(key: &str, value: &str) -> Option<String> {
    use windows_sys::Win32::System::Registry::{RegGetValueW, HKEY_CURRENT_USER, RRF_RT_REG_SZ};
    let k: Vec<u16> = key.encode_utf16().chain([0]).collect();
    let v: Vec<u16> = value.encode_utf16().chain([0]).collect();
    let mut buf = vec![0u16; 1024];
    let mut len = (buf.len() * 2) as u32;
    let rc = unsafe {
        RegGetValueW(HKEY_CURRENT_USER, k.as_ptr(), v.as_ptr(), RRF_RT_REG_SZ, std::ptr::null_mut(), buf.as_mut_ptr().cast(), &mut len)
    };
    (rc == 0).then(|| String::from_utf16_lossy(&buf[..(len as usize / 2).saturating_sub(1)]))
}

#[cfg(windows)]
fn reg_dword(key: &str, value: &str) -> Option<u32> {
    use windows_sys::Win32::System::Registry::{RegGetValueW, HKEY_CURRENT_USER, RRF_RT_REG_DWORD};
    let k: Vec<u16> = key.encode_utf16().chain([0]).collect();
    let v: Vec<u16> = value.encode_utf16().chain([0]).collect();
    let mut data = 0u32;
    let mut len = 4u32;
    let rc = unsafe {
        RegGetValueW(HKEY_CURRENT_USER, k.as_ptr(), v.as_ptr(), RRF_RT_REG_DWORD, std::ptr::null_mut(), (&mut data as *mut u32).cast(), &mut len)
    };
    (rc == 0).then_some(data)
}

/// Whether the Steam client is currently running.
pub fn steam_running() -> bool {
    #[cfg(windows)]
    {
        reg_dword("Software\\Valve\\Steam\\ActiveProcess", "pid").unwrap_or(0) != 0
    }
    #[cfg(not(windows))]
    {
        let Some(home) = dirs::home_dir() else { return false };
        std::fs::read_to_string(home.join(".steam/steam.pid"))
            .ok()
            .and_then(|p| p.trim().parse::<u32>().ok())
            .is_some_and(|pid| Path::new(&format!("/proc/{pid}")).exists())
    }
}

struct Account {
    id: u32,
    name: String,
}

/// The most recently signed-in account (loginusers.vdf), else the only/first userdata folder.
fn target_account(root: &Path) -> Option<Account> {
    const STEAMID64_BASE: u64 = 76561197960265728;
    if let Ok(text) = std::fs::read_to_string(root.join("config").join("loginusers.vdf")) {
        // Text KeyValues: "7656119..." { "AccountName" "x" "PersonaName" "y" "MostRecent" "1" ... }
        let mut users: Vec<(u64, String, bool)> = Vec::new();
        let mut cur: Option<(u64, String, bool)> = None;
        for line in text.lines() {
            let toks: Vec<&str> = line.split('"').filter(|t| !t.trim().is_empty()).map(str::trim).collect();
            if toks.len() == 1 {
                if let Ok(id) = toks[0].parse::<u64>() {
                    if let Some(u) = cur.take() {
                        users.push(u);
                    }
                    cur = Some((id, String::new(), false));
                }
            } else if toks.len() >= 2 {
                if let Some(u) = cur.as_mut() {
                    match toks[0].to_ascii_lowercase().as_str() {
                        "personaname" => u.1 = toks[1].to_string(),
                        "mostrecent" => u.2 = toks[1] == "1",
                        _ => {}
                    }
                }
            }
        }
        if let Some(u) = cur.take() {
            users.push(u);
        }
        let pick = users.iter().find(|u| u.2).or(users.first());
        if let Some((id64, name, _)) = pick {
            if *id64 > STEAMID64_BASE {
                let id = (id64 - STEAMID64_BASE) as u32;
                if root.join("userdata").join(id.to_string()).is_dir() {
                    return Some(Account { id, name: name.clone() });
                }
            }
        }
    }
    std::fs::read_dir(root.join("userdata"))
        .ok()?
        .flatten()
        .filter_map(|e| e.file_name().to_str()?.parse::<u32>().ok())
        .find(|id| *id != 0)
        .map(|id| Account { id, name: format!("Steam account {id}") })
}

// ---------- shortcut ---------------------------------------------------------------------

/// Path Steam should launch. For a Linux AppImage this is the AppImage itself.
fn launch_target() -> Result<(PathBuf, PathBuf)> {
    let exe = std::env::var_os("APPIMAGE").map(PathBuf::from).map_or_else(std::env::current_exe, Ok)?;
    let dir = exe.parent().map(Path::to_path_buf).unwrap_or_default();
    Ok((exe, dir))
}

fn quoted(p: &Path) -> String {
    format!("\"{}\"", p.display())
}

/// Steam's non-Steam shortcut id: crc32(exe + name) with the top bit set.
fn shortcut_appid(exe_quoted: &str) -> u32 {
    crc32fast::hash(format!("{exe_quoted}{APP_NAME}").as_bytes()) | 0x8000_0000
}

fn same_exe(a: &str, b: &str) -> bool {
    let norm = |s: &str| s.trim_matches('"').replace('\\', "/").to_lowercase();
    norm(a) == norm(b)
}

fn is_tunes(entry: &[(String, Value)], exe_quoted: &str) -> bool {
    get_str(entry, "Exe").is_some_and(|e| same_exe(e, exe_quoted))
        || get_str(entry, "AppName").is_some_and(|n| n == APP_NAME)
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SteamStatus {
    pub installed: bool,
    pub running: bool,
    pub added: bool,
    pub account: Option<String>,
}

struct Paths {
    shortcuts: PathBuf,
    grid: PathBuf,
    account: Account,
}

fn paths() -> Result<Paths> {
    let root = steam_root().ok_or_else(|| anyhow!("Steam isn't installed on this device"))?;
    paths_in(&root)
}

fn paths_in(root: &Path) -> Result<Paths> {
    let account = target_account(root).ok_or_else(|| anyhow!("Sign in to Steam at least once first"))?;
    let config = root.join("userdata").join(account.id.to_string()).join("config");
    Ok(Paths { shortcuts: config.join("shortcuts.vdf"), grid: config.join("grid"), account })
}

fn load_shortcuts(path: &Path) -> Result<Vec<(String, Value)>> {
    match std::fs::read(path) {
        Ok(b) if !b.is_empty() => parse_vdf(&b).context("Couldn't read Steam's shortcuts file"),
        _ => Ok(vec![("shortcuts".into(), Value::Map(Vec::new()))]),
    }
}

fn shortcuts_list(root: &mut [(String, Value)]) -> Result<&mut Vec<(String, Value)>> {
    match root.iter_mut().find(|(k, _)| k.eq_ignore_ascii_case("shortcuts")) {
        Some((_, Value::Map(m))) => Ok(m),
        _ => bail!("Steam's shortcuts file has an unexpected layout"),
    }
}

fn save_shortcuts(path: &Path, root: &[(String, Value)]) -> Result<()> {
    if path.exists() {
        std::fs::copy(path, path.with_extension("vdf.bak")).context("Couldn't back up shortcuts.vdf")?;
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    let tmp = path.with_extension("vdf.tmp");
    std::fs::write(&tmp, serialize_vdf(root))?;
    std::fs::rename(&tmp, path)?;
    Ok(())
}

pub fn status() -> SteamStatus {
    let Ok(p) = paths() else {
        return SteamStatus { installed: steam_root().is_some(), running: steam_running(), added: false, account: None };
    };
    let exe_q = launch_target().map(|(e, _)| quoted(&e)).unwrap_or_default();
    let added = load_shortcuts(&p.shortcuts)
        .ok()
        .and_then(|mut root| {
            let list = shortcuts_list(&mut root).ok()?;
            Some(list.iter().any(|(_, v)| matches!(v, Value::Map(e) if is_tunes(e, &exe_q))))
        })
        .unwrap_or(false);
    SteamStatus { installed: true, running: steam_running(), added, account: Some(p.account.name) }
}

/// Add (or update) the Tunes shortcut and install its artwork.
pub fn add() -> Result<SteamStatus> {
    add_with(paths()?, launch_target()?)?;
    Ok(status())
}

fn add_with(p: Paths, (exe, dir): (PathBuf, PathBuf)) -> Result<()> {
    let exe_q = quoted(&exe);
    let appid = shortcut_appid(&exe_q);
    let icon_path = p.grid.join(format!("{appid}_icon.png"));

    let mut root = load_shortcuts(&p.shortcuts)?;
    let list = shortcuts_list(&mut root)?;

    let fields: Vec<(String, Value)> = vec![
        ("appid".into(), Value::Int(appid as i32)),
        ("AppName".into(), Value::Str(APP_NAME.into())),
        ("Exe".into(), Value::Str(exe_q.clone())),
        ("StartDir".into(), Value::Str(quoted(&dir))),
        ("icon".into(), Value::Str(icon_path.display().to_string())),
        ("ShortcutPath".into(), Value::Str(String::new())),
        ("LaunchOptions".into(), Value::Str(String::new())),
        ("IsHidden".into(), Value::Int(0)),
        ("AllowDesktopConfig".into(), Value::Int(1)),
        ("AllowOverlay".into(), Value::Int(1)),
        ("OpenVR".into(), Value::Int(0)),
        ("Devkit".into(), Value::Int(0)),
        ("DevkitGameID".into(), Value::Str(String::new())),
        ("DevkitOverrideAppID".into(), Value::Int(0)),
        ("LastPlayTime".into(), Value::Int(0)),
        ("FlatpakAppID".into(), Value::Str(String::new())),
        ("tags".into(), Value::Map(Vec::new())),
    ];

    match list.iter_mut().find(|(_, v)| matches!(v, Value::Map(e) if is_tunes(e, &exe_q))) {
        Some((_, Value::Map(entry))) => {
            // Update in place, keeping anything Steam or the user added (tags, play time…).
            for (k, v) in fields {
                if matches!(k.as_str(), "LastPlayTime" | "tags" | "LaunchOptions" | "IsHidden") && get(entry, &k).is_some() {
                    continue;
                }
                match entry.iter_mut().find(|(ek, _)| ek.eq_ignore_ascii_case(&k)) {
                    Some(slot) => slot.1 = v,
                    None => entry.push((k, v)),
                }
            }
        }
        _ => {
            let next = list.iter().filter_map(|(k, _)| k.parse::<usize>().ok()).max().map_or(0, |n| n + 1);
            list.push((next.to_string(), Value::Map(fields)));
        }
    }
    save_shortcuts(&p.shortcuts, &root)?;

    std::fs::create_dir_all(&p.grid).context("Couldn't create Steam's artwork folder")?;
    for (suffix, bytes) in [("p", ART_CAPSULE), ("", ART_WIDE), ("_hero", ART_HERO), ("_logo", ART_LOGO), ("_icon", ART_ICON)] {
        std::fs::write(p.grid.join(format!("{appid}{suffix}.png")), bytes)?;
    }
    log::info!("added Tunes to Steam (account {}, appid {appid})", p.account.id);
    Ok(())
}

/// Remove the Tunes shortcut and its artwork.
pub fn remove() -> Result<SteamStatus> {
    remove_with(paths()?, launch_target()?.0)?;
    Ok(status())
}

fn remove_with(p: Paths, exe: PathBuf) -> Result<()> {
    let exe_q = quoted(&exe);
    let mut root = load_shortcuts(&p.shortcuts)?;
    let list = shortcuts_list(&mut root)?;
    let mut removed_ids = Vec::new();
    list.retain(|(_, v)| match v {
        Value::Map(e) if is_tunes(e, &exe_q) => {
            if let Some(Value::Int(id)) = get(e, "appid") {
                removed_ids.push(*id as u32);
            }
            false
        }
        _ => true,
    });
    // Steam expects keys "0", "1", … in order.
    for (i, (k, _)) in list.iter_mut().enumerate() {
        *k = i.to_string();
    }
    save_shortcuts(&p.shortcuts, &root)?;
    for id in removed_ids {
        for suffix in ["p", "", "_hero", "_logo", "_icon"] {
            let _ = std::fs::remove_file(p.grid.join(format!("{id}{suffix}.png")));
        }
    }
    Ok(())
}

/// Close Steam and start it again so it reloads shortcuts.
pub fn restart() -> Result<()> {
    let root = steam_root().ok_or_else(|| anyhow!("Steam isn't installed on this device"))?;
    #[cfg(windows)]
    let exe = root.join("steam.exe");
    #[cfg(not(windows))]
    let exe = PathBuf::from("steam");
    let _ = root;
    std::process::Command::new(&exe).arg("-shutdown").spawn().context("Couldn't ask Steam to close")?;
    let start = std::time::Instant::now();
    while steam_running() && start.elapsed() < std::time::Duration::from_secs(45) {
        std::thread::sleep(std::time::Duration::from_millis(500));
    }
    if steam_running() {
        bail!("Steam didn't close in time; please restart it yourself");
    }
    std::thread::sleep(std::time::Duration::from_secs(2));
    std::process::Command::new(&exe).spawn().context("Couldn't start Steam")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vdf_round_trip() {
        let root = vec![(
            "shortcuts".to_string(),
            Value::Map(vec![(
                "0".into(),
                Value::Map(vec![
                    ("appid".into(), Value::Int(-123456)),
                    ("AppName".into(), Value::Str("Some Game".into())),
                    ("Exe".into(), Value::Str("\"C:\\Games\\game.exe\"".into())),
                    ("LastPlayTime".into(), Value::Int(1700000000)),
                    ("tags".into(), Value::Map(vec![("0".into(), Value::Str("favorite".into()))])),
                ]),
            )]),
        )];
        let bytes = serialize_vdf(&root);
        assert_eq!(parse_vdf(&bytes).unwrap(), root);
        assert_eq!(serialize_vdf(&parse_vdf(&bytes).unwrap()), bytes);
    }

    /// Add → add again → remove against a fake Steam folder holding another game's shortcut.
    #[test]
    fn add_update_remove_preserves_other_shortcuts() {
        let root = std::env::temp_dir().join(format!("tunes-steam-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let config = root.join("userdata").join("12345").join("config");
        std::fs::create_dir_all(&config).unwrap();
        std::fs::create_dir_all(root.join("config")).unwrap();
        std::fs::write(
            root.join("config").join("loginusers.vdf"),
            "\"users\"
{
	\"76561197960278073\"
	{
		\"PersonaName\"		\"Tester\"
		\"MostRecent\"		\"1\"
	}
}
",
        )
        .unwrap();
        let other = vec![(
            "shortcuts".to_string(),
            Value::Map(vec![(
                "0".into(),
                Value::Map(vec![
                    ("appid".into(), Value::Int(-555)),
                    ("AppName".into(), Value::Str("Other Game".into())),
                    ("Exe".into(), Value::Str(r#""C:\Games\other.exe""#.into())),
                    ("tags".into(), Value::Map(vec![("0".into(), Value::Str("favorite".into()))])),
                ]),
            )]),
        )];
        std::fs::write(config.join("shortcuts.vdf"), serialize_vdf(&other)).unwrap();

        let exe = PathBuf::from(r"C:\Apps\Tunes\tunes.exe");
        let target = || (exe.clone(), PathBuf::from(r"C:\Apps\Tunes"));
        let p = || paths_in(&root).unwrap();
        assert_eq!(p().account.name, "Tester");
        assert_eq!(p().account.id, 12345);

        add_with(p(), target()).unwrap();
        add_with(p(), target()).unwrap(); // idempotent: updates, no duplicate
        let mut parsed = parse_vdf(&std::fs::read(config.join("shortcuts.vdf")).unwrap()).unwrap();
        let list = shortcuts_list(&mut parsed).unwrap().clone();
        assert_eq!(list.len(), 2);
        assert_eq!(list[0], other_entry(&other));
        let Value::Map(t) = &list[1].1 else { panic!() };
        assert_eq!(get_str(t, "AppName"), Some("Tunes"));
        let id = shortcut_appid(&quoted(&exe));
        assert_eq!(get(t, "appid"), Some(&Value::Int(id as i32)));
        for suffix in ["p", "", "_hero", "_logo", "_icon"] {
            assert!(config.join("grid").join(format!("{id}{suffix}.png")).exists(), "missing art {suffix}");
        }
        assert!(config.join("shortcuts.vdf.bak").exists());

        remove_with(p(), exe.clone()).unwrap();
        let mut parsed = parse_vdf(&std::fs::read(config.join("shortcuts.vdf")).unwrap()).unwrap();
        let list = shortcuts_list(&mut parsed).unwrap().clone();
        assert_eq!(list, vec![other_entry(&other)]);
        assert!(!config.join("grid").join(format!("{id}_hero.png")).exists());
        let _ = std::fs::remove_dir_all(&root);
    }

    fn other_entry(root: &[(String, Value)]) -> (String, Value) {
        let Value::Map(m) = &root[0].1 else { panic!() };
        m[0].clone()
    }

    #[test]
    fn appid_has_top_bit() {
        assert!(shortcut_appid("\"C:\\Tunes\\tunes.exe\"") & 0x8000_0000 != 0);
    }
}
